export const ICON_NAMES = Object.keys(ICONS).sort();

export function CatalogIcon({ name, ...props }: { name: string | null | undefined } & LucideProps) {
  const Icon = (name && ICONS[name]) || CodeIcon;
  return <Icon aria-hidden="true" {...props} />;
}
